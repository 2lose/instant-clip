# Encrypts the build's secrets into a generated header (build\gen\embedded-secrets.inc,
# never committed). Plaintext only lives in git-ignored secrets\*.txt files (or env vars):
#
#   secrets\update-token.txt         INSTANT_CLIP_UPDATE_TOKEN   read-only token for update checks
#   secrets\feedback-relay-url.txt   INSTANT_CLIP_FEEDBACK_URL   feedback relay endpoint (Cloudflare Worker)
#   secrets\feedback-relay-key.txt   INSTANT_CLIP_FEEDBACK_KEY   shared key the relay checks
#
# Each value gets its own random AES-256 key, split in two arrays. This keeps them out of
# `strings`-style inspection only; the Discord webhook itself never enters the plugin.
param([Parameter(Mandatory)][string]$Out)

$ErrorActionPreference = "Stop"
$secretsDir = Join-Path $PSScriptRoot "..\secrets"

function Get-Secret([string]$file, [string]$envName) {
    $value = [Environment]::GetEnvironmentVariable($envName)
    $path = Join-Path $secretsDir $file
    if (-not $value -and (Test-Path $path)) { $value = ([IO.File]::ReadAllText($path)).Trim() }
    return $value
}

function Format-Bytes([byte[]]$bytes) {
    if ($bytes.Length -eq 0) { return "0" }
    ($bytes | ForEach-Object { "0x{0:x2}" -f $_ }) -join ", "
}

$rng = [Security.Cryptography.RandomNumberGenerator]::Create()
function New-Blob([string]$name, [string]$value) {
    if (-not $value) {
        return "static const EmbeddedBlob $name = {nullptr, 0, {0}, {0}, {0}};`n"
    }
    $key = New-Object byte[] 32; $rng.GetBytes($key)
    $iv = New-Object byte[] 16; $rng.GetBytes($iv)
    $mask = New-Object byte[] 32; $rng.GetBytes($mask)
    $aes = [Security.Cryptography.Aes]::Create()
    $aes.Mode = [Security.Cryptography.CipherMode]::CBC
    $aes.Padding = [Security.Cryptography.PaddingMode]::PKCS7
    $aes.Key = $key
    $aes.IV = $iv
    $plain = [Text.Encoding]::UTF8.GetBytes($value)
    $cipher = $aes.CreateEncryptor().TransformFinalBlock($plain, 0, $plain.Length)
    $aes.Dispose()
    $keyA = New-Object byte[] 32
    for ($i = 0; $i -lt 32; $i++) { $keyA[$i] = $key[$i] -bxor $mask[$i] }
    return "static const unsigned char ${name}_c[] = {$(Format-Bytes $cipher)};`n" +
        "static const EmbeddedBlob $name = {${name}_c, sizeof(${name}_c), {$(Format-Bytes $iv)}, " +
        "{$(Format-Bytes $keyA)}, {$(Format-Bytes $mask)}};`n"
}

$values = [ordered]@{
    kUpdateToken = Get-Secret "update-token.txt" "INSTANT_CLIP_UPDATE_TOKEN"
    kFeedbackUrl = Get-Secret "feedback-relay-url.txt" "INSTANT_CLIP_FEEDBACK_URL"
    kFeedbackKey = Get-Secret "feedback-relay-key.txt" "INSTANT_CLIP_FEEDBACK_KEY"
}

$header = "// Generated by scripts/embed-secrets.ps1. Do not commit.`n"
foreach ($name in $values.Keys) { $header += New-Blob $name $values[$name] }

New-Item -ItemType Directory -Force (Split-Path $Out -Parent) | Out-Null
[IO.File]::WriteAllText($Out, $header)

$present = ($values.Keys | Where-Object { $values[$_] }) -join ", "
$missing = ($values.Keys | Where-Object { -not $values[$_] }) -join ", "
Write-Host "embed-secrets: embedded [$present]$(if ($missing) { "; missing [$missing]" })" -ForegroundColor $(if ($missing) { "Yellow" } else { "Green" })

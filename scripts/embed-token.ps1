# Encrypts the update token into a generated header so the plugin can read the private
# release repo on any PC. The plaintext token only lives in secrets\update-token.txt
# (git-ignored) or the INSTANT_CLIP_UPDATE_TOKEN environment variable.
#
# This is obfuscation, not secrecy: the DLL carries the key to decrypt it. Use a
# fine-grained token with read-only Contents access to the release repo only.
param([Parameter(Mandatory)][string]$Out)

$ErrorActionPreference = "Stop"

$token = $env:INSTANT_CLIP_UPDATE_TOKEN
$file = Join-Path $PSScriptRoot "..\secrets\update-token.txt"
if (-not $token -and (Test-Path $file)) { $token = ([IO.File]::ReadAllText($file)).Trim() }

New-Item -ItemType Directory -Force (Split-Path $Out -Parent) | Out-Null

function Format-Bytes([byte[]]$bytes) {
    ($bytes | ForEach-Object { "0x{0:x2}" -f $_ }) -join ", "
}

if (-not $token) {
    [IO.File]::WriteAllText($Out, "// No update token embedded (secrets\update-token.txt missing).`n" +
        "static const unsigned char kTokCipher[1] = {0};`nstatic const unsigned char kTokIv[16] = {0};`n" +
        "static const unsigned char kTokKeyA[32] = {0};`nstatic const unsigned char kTokKeyB[32] = {0};`n" +
        "static constexpr size_t kTokCipherLen = 0;`n")
    Write-Host "embed-token: no token found, building without one" -ForegroundColor Yellow
    return
}

$rng = [Security.Cryptography.RandomNumberGenerator]::Create()
$key = New-Object byte[] 32; $rng.GetBytes($key)
$iv = New-Object byte[] 16; $rng.GetBytes($iv)
$mask = New-Object byte[] 32; $rng.GetBytes($mask)

$aes = [Security.Cryptography.Aes]::Create()
$aes.Mode = [Security.Cryptography.CipherMode]::CBC
$aes.Padding = [Security.Cryptography.PaddingMode]::PKCS7
$aes.Key = $key
$aes.IV = $iv
$plain = [Text.Encoding]::UTF8.GetBytes($token)
$cipher = $aes.CreateEncryptor().TransformFinalBlock($plain, 0, $plain.Length)
$aes.Dispose()

# The key is stored split in two arrays (key = A xor B) so it never appears whole.
$keyA = New-Object byte[] 32
for ($i = 0; $i -lt 32; $i++) { $keyA[$i] = $key[$i] -bxor $mask[$i] }

$header = @"
// Generated by scripts/embed-token.ps1. Do not commit.
static const unsigned char kTokCipher[] = {$(Format-Bytes $cipher)};
static const unsigned char kTokIv[16] = {$(Format-Bytes $iv)};
static const unsigned char kTokKeyA[32] = {$(Format-Bytes $keyA)};
static const unsigned char kTokKeyB[32] = {$(Format-Bytes $mask)};
static constexpr size_t kTokCipherLen = sizeof(kTokCipher);
"@
[IO.File]::WriteAllText($Out, $header)
Write-Host "embed-token: token encrypted into $(Split-Path $Out -Leaf)" -ForegroundColor Green
